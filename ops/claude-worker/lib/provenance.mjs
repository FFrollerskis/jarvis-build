/**
 * COMMIT-AUTHORSHIP EVIDENCE (D-134, PR #80 review).
 *
 * ------------------------------------------------------------------------
 * THE DEFECT THIS MODULE CLOSES
 * ------------------------------------------------------------------------
 *
 * D-132 recorded `head_before`, `head_after` and `observed_heads`, and D-133
 * handed them to a resumed child with this sentence:
 *
 *     "HEAD ADVANCED during that attempt, so commits in that range are THIS
 *      TASK'S OWN WORK."
 *
 * That inference is invalid. `head_before != head_after` is an OBSERVATION of
 * two reads taken at two moments. It says a ref moved between them. It says
 * nothing whatsoever about WHO moved it. Any process with access to that
 * directory - the user, an editor, a script, a second worker instance, a stray
 * `git pull` - can advance the ref inside the attempt window, and the worker's
 * two reads cannot tell that apart from work its own child did.
 *
 * Acting on an invalid inference is not a cosmetic problem: the prompt built on
 * it told the child "these commits are yours, build on them", which is exactly
 * how a foreign commit gets adopted as task output and shipped.
 *
 * ------------------------------------------------------------------------
 * TWO DIFFERENT KINDS OF ATTRIBUTION, DELIBERATELY NOT MERGED
 * ------------------------------------------------------------------------
 *
 * DIRECTORY / DIRTY-STATE attribution (`lib/worktree.mjs`) is sound by
 * CONSTRUCTION. The worker creates an empty worktree at a known baseline, writes
 * a durable claim binding that directory to one task BEFORE anything is touched,
 * and points exactly one child at it. Uncommitted changes found there later are
 * task-owned because nothing else was ever aimed at that directory. Ownership is
 * asserted FORWARD and only ever CHECKED afterwards.
 *
 * COMMIT authorship does NOT follow from that. The claim covers the directory,
 * not every write into it, and a commit is a durable, publishable artefact that
 * will end up in a PR. It therefore needs its own positive evidence, and this
 * module is that evidence:
 *
 *   Each dispatch attempt has a fresh random `attempt_id`, generated by the
 *   worker, recorded durably in the claim and in worker state BEFORE the child
 *   exists, and handed to that child alone. A commit that carries
 *
 *       Jarvis-Task-Id: <TASK_ID>
 *       Jarvis-Attempt-Id: <attempt_id>
 *
 *   in its message is bound to that exact task and that exact attempt, because
 *   the value came into existence for this attempt and was given to nobody else.
 *   An unrelated writer producing a commit in the same window does not have it.
 *
 * HONEST LIMIT, stated rather than hidden: this is evidence against UNRELATED
 * writers - other tools, the user's own commands, a concurrent worker, a stray
 * script. It is NOT protection against a deliberate forger who already has read
 * access to the host, since the attempt id is durable on disk and ends up in a
 * published commit message. The worker cannot prove authorship against an
 * attacker who already owns the machine, and does not claim to.
 *
 * ------------------------------------------------------------------------
 * WHAT THE WORKER DOES WITH THE VERDICT
 * ------------------------------------------------------------------------
 *
 * Only `unchanged` and `task_attributed` are VERIFIED. Everything else -
 * a partially attributed range, an unattributed range, a rewound ref, or a
 * question git could not answer - is UNVERIFIED, and unverified resumes
 * FAIL-CLOSED in exactly one direction:
 *
 *   PRESERVE the commits, tell the child they are of UNKNOWN authorship, tell it
 *   to verify and reconcile FORWARD, and explicitly forbid every destructive
 *   reconciliation (stash, reset, revert, clean, checkout over, force-push,
 *   re-applying an older snapshot).
 *
 * Fail-closed here means "do not adopt AND do not destroy". Unverified work is
 * not the same as unwanted work, and the worker has no authority to decide which
 * it is.
 */

import { spawnSync } from "node:child_process";

import { gitIsAncestor, gitLogRange } from "./git.mjs";

/** The trailer keys. Matched case-insensitively, emitted in this exact casing. */
export const TRAILER_TASK = "Jarvis-Task-Id";
export const TRAILER_ATTEMPT = "Jarvis-Attempt-Id";

/** Env names the child also receives, so a shell helper need not parse the prompt. */
export const ENV_TASK_ID = "JARVIS_TASK_ID";
export const ENV_ATTEMPT_ID = "JARVIS_TASK_ATTEMPT_ID";

export const COMMIT_PROVENANCE = Object.freeze({
  /** HEAD did not move. There is no authorship question to answer. */
  UNCHANGED: "unchanged",
  /** Every commit in the range carries this task's own attempt evidence. */
  ATTRIBUTED: "task_attributed",
  /** Some commits carry it and some do not - a foreign writer was involved. */
  PARTIAL: "partially_attributed",
  /** The range is real but NOTHING in it is bound to this task. */
  UNATTRIBUTED: "unattributed",
  /** `head_after` is not a descendant of `head_before`: the ref was rewound. */
  DIVERGED: "diverged",
  /** The ref moved AGAIN after the attempt ended, outside any attempt window. */
  DRIFTED: "drifted_after_attempt",
  /** Git could not answer, or the heads are not usable. Never read as "clean". */
  UNKNOWN: "unknown"
});

/** The only two verdicts that may ever be presented to a child as its own work. */
export const VERIFIED_VERDICTS = Object.freeze([
  COMMIT_PROVENANCE.UNCHANGED,
  COMMIT_PROVENANCE.ATTRIBUTED
]);

export function isVerifiedVerdict(verdict) {
  return VERIFIED_VERDICTS.includes(verdict);
}

const SHA_RE = /^[0-9a-f]{7,40}$/i;

/**
 * D-135: TWO DIFFERENT BOUNDS, deliberately not the same number and deliberately
 * not the same KIND of bound. Conflating them is what produced the PR #80
 * false-verification edge:
 *
 *     for (const commit of commits.slice(0, MAX_RECORDED_COMMITS)) { ... }
 *
 * That loop bounded the DECISION as a side effect of bounding the RECORD. A
 * range of 51 commits whose first 50 carried this task's trailers and whose 51st
 * was a foreign commit was classified `task_attributed`, `verified: true` - the
 * one commit that mattered was never looked at, and the verdict said the
 * opposite of the truth. A bound on evidence storage must never become a bound
 * on evidence evaluation.
 *
 *   MAX_EXAMINED_COMMITS         how many commits we are willing to READ AND
 *                                CLASSIFY. Every commit inside this bound is
 *                                examined; a range LARGER than it is not
 *                                partially trusted, it is UNVERIFIED as a whole
 *                                (`unknown`), because commits we never read
 *                                cannot be vouched for.
 *
 *   MAX_RECORDED_COMMIT_DETAILS  how many per-commit DETAIL ROWS a single record
 *                                may persist, per list, so state.json cannot grow
 *                                without limit. Truncating this list never
 *                                changes a verdict: the counts are always the
 *                                FULL counts, and `details_truncated` says so.
 */
const MAX_EXAMINED_COMMITS = 1000;
const MAX_RECORDED_COMMIT_DETAILS = 50;

export { MAX_EXAMINED_COMMITS, MAX_RECORDED_COMMIT_DETAILS };

function usableSha(value) {
  return typeof value === "string" && SHA_RE.test(value.trim());
}

/** The two lines a child must append to every commit it makes. */
export function commitTrailerLines({ taskId, attemptId }) {
  return [`${TRAILER_TASK}: ${taskId}`, `${TRAILER_ATTEMPT}: ${attemptId}`];
}

/**
 * Read the evidence trailers out of a commit message.
 *
 * Anchored per line and whitespace-tolerant, but NOT fuzzy: the value must be a
 * single token and is compared later by exact string equality. A trailer that
 * merely mentions the task somewhere in prose is not evidence.
 */
export function parseCommitEvidence(message) {
  const taskIds = [];
  const attemptIds = [];
  for (const raw of String(message ?? "").split(/\r?\n/)) {
    const line = raw.trim();
    const task = new RegExp(`^${TRAILER_TASK}:\\s*(\\S+)\\s*$`, "i").exec(line);
    if (task) {
      taskIds.push(task[1]);
      continue;
    }
    const attempt = new RegExp(`^${TRAILER_ATTEMPT}:\\s*(\\S+)\\s*$`, "i").exec(line);
    if (attempt) attemptIds.push(attempt[1]);
  }
  return { taskIds, attemptIds };
}

/**
 * Is this ONE commit positively bound to this task and one of its attempts?
 *
 * Both halves are required. The task id alone is guessable from any public
 * comment on the control issue; the attempt id alone does not say which task it
 * belonged to. Only the pair, both matched EXACTLY, is evidence.
 */
export function commitIsAttributed(commit, { taskId, attemptIds }) {
  const known = new Set((attemptIds ?? []).filter((a) => typeof a === "string" && a.length > 0));
  if (known.size === 0) return { attributed: false, attemptId: null, reason: "no_known_attempt_id" };
  const { taskIds, attemptIds: found } = parseCommitEvidence(commit?.message);
  if (!taskIds.includes(taskId)) return { attributed: false, attemptId: null, reason: "no_matching_task_trailer" };
  const match = found.find((a) => known.has(a));
  if (!match) return { attributed: false, attemptId: null, reason: "no_matching_attempt_trailer" };
  return { attributed: true, attemptId: match, reason: "task_and_attempt_trailer_match" };
}

/**
 * Turn raw observations into a verdict. Pure: every branch is unit-testable and
 * no branch can reach the filesystem.
 *
 * `range` is `{ ok, isAncestor, commits, error }` as produced by
 * `collectCommitProvenance`; `isAncestor === null` means git could not say.
 */
export function classifyCommitRange({ taskId, attemptIds, headBefore, headAfter, range = {} }) {
  const base = {
    head_before: usableSha(headBefore) ? headBefore : null,
    head_after: usableSha(headAfter) ? headAfter : null,
    checked_at: new Date().toISOString(),
    attributed_commits: [],
    unattributed_commits: [],
    // D-135: the COUNTS are the decision surface; the arrays above are only the
    // bounded human-readable detail. They are initialised here so every early
    // return carries the same shape and no consumer has to guess.
    commit_count: 0,
    examined_commit_count: 0,
    attributed_count: 0,
    unattributed_count: 0,
    details_truncated: false,
    range_truncated: range.truncated === true,
    error: range.error ?? null
  };

  if (!base.head_before || !base.head_after) {
    return {
      ...base,
      verdict: COMMIT_PROVENANCE.UNKNOWN,
      verified: false,
      reason: "head_before_or_head_after_is_not_a_usable_commit_id"
    };
  }

  if (base.head_before === base.head_after) {
    return { ...base, verdict: COMMIT_PROVENANCE.UNCHANGED, verified: true, reason: "head_did_not_move" };
  }

  if (range.ok !== true) {
    return {
      ...base,
      verdict: COMMIT_PROVENANCE.UNKNOWN,
      verified: false,
      reason: `commit_range_could_not_be_read (${range.error ?? "unknown"})`
    };
  }

  if (range.isAncestor === false) {
    // The ref did not advance - it was replaced. Whatever produced that, it was
    // not an ordinary commit, and the old tip may no longer be reachable.
    return {
      ...base,
      verdict: COMMIT_PROVENANCE.DIVERGED,
      verified: false,
      reason: "head_after_is_not_a_descendant_of_head_before (the ref was rewound or replaced)"
    };
  }
  if (range.isAncestor !== true) {
    return {
      ...base,
      verdict: COMMIT_PROVENANCE.UNKNOWN,
      verified: false,
      reason: `ancestry_could_not_be_determined (${range.error ?? "unknown"})`
    };
  }

  // D-135: A RANGE WE DID NOT READ IN FULL IS NOT A RANGE WE MAY CLASSIFY.
  //
  // This is checked BEFORE the commits are looked at, so no prefix of a
  // truncated range can reach the attribution loop and produce a verdict about
  // commits nobody examined. Fail-closed: `unknown`, never `task_attributed`.
  if (range.truncated === true) {
    return {
      ...base,
      commit_count: null,
      examined_commit_count: Array.isArray(range.commits) ? range.commits.length : 0,
      verdict: COMMIT_PROVENANCE.UNKNOWN,
      verified: false,
      reason: `the commit range is larger than this worker will examine (more than ${MAX_EXAMINED_COMMITS} `
        + "commits), so at least one commit in it was never read; an unexamined commit is never vouched for"
    };
  }

  const commits = Array.isArray(range.commits) ? range.commits : [];
  if (commits.length === 0) {
    // Heads differ but the range is empty. Nothing here is explicable, so it is
    // not verified, whatever the ancestry query said.
    return {
      ...base,
      verdict: COMMIT_PROVENANCE.UNKNOWN,
      verified: false,
      reason: "heads_differ_but_the_commit_range_is_empty"
    };
  }

  // --- D-135: EVERY commit in the range is classified. No slice, no prefix. ---
  //
  // The counts below drive the verdict and are always the FULL counts. Only the
  // two detail lists are capped, and capping them is visible in the record
  // (`details_truncated`) rather than silent.
  const attributed = [];
  const unattributed = [];
  let attributedCount = 0;
  let unattributedCount = 0;
  let detailsTruncated = false;

  for (const commit of commits) {
    const verdict = commitIsAttributed(commit, { taskId, attemptIds });
    const row = {
      sha: commit.sha,
      subject: String(commit.message ?? "").split(/\r?\n/)[0]?.slice(0, 120) ?? "",
      committed_at: commit.committed_at ?? null,
      author: commit.author_email ? `${commit.author_name} <${commit.author_email}>` : (commit.author_name ?? null)
    };
    if (verdict.attributed) {
      attributedCount += 1;
      if (attributed.length < MAX_RECORDED_COMMIT_DETAILS) attributed.push({ ...row, attempt_id: verdict.attemptId });
      else detailsTruncated = true;
    } else {
      unattributedCount += 1;
      if (unattributed.length < MAX_RECORDED_COMMIT_DETAILS) unattributed.push({ ...row, reason: verdict.reason });
      else detailsTruncated = true;
    }
  }

  const out = {
    ...base,
    attributed_commits: attributed,
    unattributed_commits: unattributed,
    commit_count: commits.length,
    examined_commit_count: commits.length,
    attributed_count: attributedCount,
    unattributed_count: unattributedCount,
    details_truncated: detailsTruncated
  };

  // `unattributedCount`, not `unattributed.length`: the detail list is capped and
  // the count is not, so a foreign commit past the detail cap still decides.
  if (unattributedCount === 0) {
    return {
      ...out,
      verdict: COMMIT_PROVENANCE.ATTRIBUTED,
      verified: true,
      reason: `every commit in the range carries this task's own attempt evidence (${attributedCount} of ${commits.length} examined)`
    };
  }
  if (attributedCount === 0) {
    return {
      ...out,
      verdict: COMMIT_PROVENANCE.UNATTRIBUTED,
      verified: false,
      reason: `no commit in the range carries this task's attempt evidence (${unattributedCount} unexplained)`
    };
  }
  return {
    ...out,
    verdict: COMMIT_PROVENANCE.PARTIAL,
    verified: false,
    reason: `the range mixes this task's commits (${attributedCount}) with commits it cannot account for (${unattributedCount})`
  };
}

/**
 * Read the actual repository and classify. Effectful half of the module.
 *
 * `wtCfg` must already point at the TASK'S OWN worktree (`atPath`). Reading the
 * primary checkout here would classify the user's history as a task's output -
 * the same category error this module exists to remove.
 *
 * No git command runs at all when the heads are equal or unusable: there is
 * nothing to classify, and a needless subprocess is a needless failure mode.
 */
export function collectCommitProvenance(wtCfg, { taskId, attemptIds, headBefore, headAfter }, runner = spawnSync) {
  if (!usableSha(headBefore) || !usableSha(headAfter) || headBefore === headAfter) {
    return classifyCommitRange({ taskId, attemptIds, headBefore, headAfter, range: {} });
  }
  const ancestry = gitIsAncestor(wtCfg, headBefore, headAfter, runner);
  if (!ancestry.ok) {
    return classifyCommitRange({
      taskId, attemptIds, headBefore, headAfter,
      range: { ok: false, error: ancestry.error }
    });
  }
  if (ancestry.isAncestor === false) {
    return classifyCommitRange({
      taskId, attemptIds, headBefore, headAfter,
      range: { ok: true, isAncestor: false, commits: [] }
    });
  }
  // D-135: bounded READ, and the bound is reported rather than hidden. A range
  // bigger than `MAX_EXAMINED_COMMITS` comes back `truncated: true`, which
  // `classifyCommitRange` turns into `unknown` - not into a verdict about the
  // prefix git happened to return first.
  const log = gitLogRange(wtCfg, headBefore, headAfter, runner, { limit: MAX_EXAMINED_COMMITS });
  return classifyCommitRange({
    taskId, attemptIds, headBefore, headAfter,
    range: { ok: log.ok, isAncestor: true, commits: log.commits, truncated: log.truncated === true, error: log.error ?? null }
  });
}

/**
 * The record a resumed attempt should act on, given what was durably stored at
 * the END of the previous attempt and what the worktree's HEAD is RIGHT NOW.
 *
 * The stored verdict was true when it was computed. Between then and now the
 * worktree has been sitting on disk with nobody watching it, so a stored
 * "verified" verdict is only still usable if HEAD has not moved since. Drift
 * downgrades it - it never upgrades anything, and it never rewrites history.
 */
export function provenanceForResume({ record, headNow, headBefore = null, headAfter = null }) {
  const stored = record && typeof record === "object" ? record : null;
  const fallback = {
    verdict: COMMIT_PROVENANCE.UNKNOWN,
    verified: false,
    head_before: usableSha(headBefore) ? headBefore : null,
    head_after: usableSha(headAfter) ? headAfter : null,
    attributed_commits: [],
    unattributed_commits: [],
    reason: "no commit-authorship evidence was recorded for the previous attempt",
    error: null,
    checked_at: null
  };

  const basis = stored ?? ((fallback.head_before || fallback.head_after) ? fallback : null);
  if (!basis) return null;

  // A verdict we cannot re-confirm is not a verdict we may still rely on. An
  // unreadable HEAD downgrades a verified record and leaves an unverified one
  // exactly as unverified as it already was.
  if (!usableSha(headNow)) {
    const wasVerified = isVerifiedVerdict(basis.verdict);
    return {
      ...basis,
      head_now: null,
      drifted: null,
      verified: false,
      verdict: wasVerified ? COMMIT_PROVENANCE.UNKNOWN : basis.verdict,
      reason: wasVerified
        ? `${basis.reason}; but the worktree's current HEAD could not be read, so that verdict cannot be re-confirmed`
        : basis.reason
    };
  }

  const recordedAfter = usableSha(basis.head_after) ? basis.head_after : null;
  if (recordedAfter && recordedAfter !== headNow) {
    return {
      ...basis,
      head_now: headNow,
      drifted: true,
      verdict: COMMIT_PROVENANCE.DRIFTED,
      verified: false,
      reason: `the worktree HEAD is now ${headNow}, but the previous attempt ended at ${recordedAfter}. `
        + "Something moved the ref while no attempt was running, so nothing at or below the current tip "
        + "can be presented as this task's proven work."
    };
  }

  return { ...basis, head_now: headNow, drifted: false };
}

/**
 * The prompt lines for a resumed child. This is where the whole module either
 * tells the truth or lies, so the two cases are written out in full rather than
 * assembled from a shared template with a flipped adjective.
 */
export function describeCommitProvenance(prov) {
  if (!prov) return [];

  const heads = `Recorded observation: the previous attempt was seen at HEAD ${prov.head_before ?? "unknown"} `
    + `when it started and at HEAD ${prov.head_after ?? "unknown"} when it ended`
    + `${prov.head_now && prov.head_now !== prov.head_after ? `; the worktree is at HEAD ${prov.head_now} right now` : ""}.`;

  if (prov.verdict === COMMIT_PROVENANCE.UNCHANGED) {
    return [
      "COMMIT PROVENANCE: HEAD did not move during the previous attempt "
        + `(still ${prov.head_after ?? prov.head_before ?? "unknown"}). No commit-authorship question arises.`,
      ""
    ];
  }

  // D-135: the detail lists are capped; the counts are not. Say so explicitly
  // whenever the two differ, so "5 commits listed" is never read as "5 commits".
  const listNote = (shown, total) => (Number.isFinite(total) && total > shown
    ? [`  (${shown} of ${total} shown - the detail list is capped; the verdict covers ALL ${total})`]
    : []);

  if (prov.verdict === COMMIT_PROVENANCE.ATTRIBUTED) {
    return [
      "COMMIT PROVENANCE: VERIFIED AS THIS TASK'S OWN WORK.",
      heads,
      `Every commit in that range carries this task's own evidence trailers (${TRAILER_TASK} and `
        + `${TRAILER_ATTEMPT} matching an attempt id issued to this task alone), which is what makes them `
        + "provably yours rather than merely concurrent:",
      ...prov.attributed_commits.map((c) => `  ${c.sha} ${c.subject}`),
      ...listNote(prov.attributed_commits?.length ?? 0, prov.attributed_count),
      "Treat them as yours: verify them and build on them. Never stash, reset, force-push, revert or",
      "re-apply an older snapshot over them, and never treat them as foreign or unknown changes.",
      "If the repository is now AHEAD of those commits, the newer state is authoritative. Reconcile",
      "forward against it; do not attempt to restore the older state.",
      ""
    ];
  }

  // --- everything below is UNVERIFIED and must fail closed in BOTH directions ---
  const why = {
    [COMMIT_PROVENANCE.UNATTRIBUTED]: "none of the commits carry this task's evidence trailers, so an "
      + "unrelated writer is the equally likely explanation",
    [COMMIT_PROVENANCE.PARTIAL]: "the range MIXES commits that carry this task's evidence trailers with "
      + "commits that do not, so at least one writer other than this task was involved",
    [COMMIT_PROVENANCE.DIVERGED]: "the ref did not advance - it was REWOUND or REPLACED, which no ordinary "
      + "commit does",
    [COMMIT_PROVENANCE.DRIFTED]: "the ref moved again AFTER the previous attempt had already ended, i.e. "
      + "while no attempt of this task was running at all",
    [COMMIT_PROVENANCE.UNKNOWN]: "the question could not be answered, and an unanswered question is never "
      + "read as a clean answer"
  }[prov.verdict] ?? "the evidence does not bind these commits to this task";

  return [
    "COMMIT PROVENANCE: UNVERIFIED. DO NOT TREAT THE CHANGED HEAD AS YOUR OWN WORK.",
    heads,
    "A moved HEAD is an OBSERVATION, not proof of authorship. The worker reads the ref twice and cannot",
    "see who moved it in between; any process with access to this worktree can advance it. In this case "
      + `${why}.`,
    prov.reason ? `Recorded reason: ${prov.reason}` : "",
    ...(prov.unattributed_commits?.length > 0
      ? ["Commits that are NOT accounted for by this task:",
        ...prov.unattributed_commits.map((c) => `  ${c.sha} ${c.subject}`),
        ...listNote(prov.unattributed_commits.length, prov.unattributed_count)]
      : []),
    ...(prov.attributed_commits?.length > 0
      ? ["Commits that ARE bound to this task by evidence trailers:",
        ...prov.attributed_commits.map((c) => `  ${c.sha} ${c.subject}`),
        ...listNote(prov.attributed_commits.length, prov.attributed_count)]
      : []),
    "",
    "REQUIRED HANDLING - fail closed in BOTH directions:",
    "  1. PRESERVE everything. Never stash, reset, revert, clean, checkout over, force-push, rebase or",
    "     re-apply an older snapshot over these commits. Unverified is NOT the same as unwanted, and you",
    "     have no authority to decide that it is.",
    "  2. Do NOT adopt them as this task's output, do NOT report them as your work, and do NOT build on",
    "     them until you have verified for yourself - against the actual diff, the PR and CI - what they",
    "     are and whether they belong in this task's deliverable.",
    "  3. Reconcile FORWARD from the current state. If you cannot establish what these commits are, say",
    "     so explicitly in your report and stop; a blocked report against preserved work is the correct",
    "     outcome, and is strictly better than a confident one built on an unproven assumption.",
    ""
  ];
}

/**
 * The instruction block that makes the evidence exist in the first place.
 *
 * Stated as a mandatory part of the task, with the consequence of omitting it
 * spelled out: a child that silently drops the trailers does not lose its work,
 * it STRANDS it, because a later resume can no longer prove the commits are the
 * task's own.
 */
export function describeCommitEvidenceRequirement({ taskId, attemptId }) {
  if (!taskId || !attemptId) return [];
  return [
    "COMMIT EVIDENCE (D-134, mandatory for every commit you make in this worktree):",
    "End every commit message with these two trailer lines, each on its own line, after any",
    "Co-Authored-By line:",
    ...commitTrailerLines({ taskId, attemptId }).map((l) => `    ${l}`),
    `The attempt id is a fresh value generated for THIS attempt only and given to you alone (also`,
    `exported as ${ENV_ATTEMPT_ID}; the task id is exported as ${ENV_TASK_ID}). It is the ONLY positive`,
    "evidence that binds a commit to this task and attempt and excludes an unrelated writer - the worker",
    "reading HEAD before and after proves nothing about who moved it.",
    "A commit without these trailers cannot be proven to be yours. A later resume must then treat it as",
    "an UNVERIFIED change of unknown authorship: preserved, never destroyed, but also never adopted as",
    "this task's output. Omitting the trailers does not lose work - it strands it.",
    ""
  ];
}

/* ==========================================================================
 * THE COMPLETION GATE (D-135)
 * ==========================================================================
 *
 * D-134 answered the authorship question honestly and then did nothing with the
 * answer. `commit_provenance` was computed, logged, persisted and handed to a
 * resumed child - and the very next branch in `worker.mjs` was:
 *
 *     if (completion.complete) { ... status: COMPLETED, successful: ...,
 *                                emit COMPLETION_CONFIRMED,
 *                                releaseWorktreeIfSettled(...) ... }
 *
 * with no reference to the verdict at all. So the adversarial case the D-134
 * tests set up - an unrelated writer advances the claimed worktree's HEAD inside
 * the attempt window - still ended in a clean success IF the child also posted a
 * trusted `STATUS=COMPLETE`: the task was marked completed AND successful, the
 * worktree holding the unexplained commit was released, and - because the queue
 * asks the FRESH control issue whether a task "completed successfully" - that
 * record went on to retire strictly older, still-valid tasks. Three fail-open
 * consequences from one missing condition.
 *
 * The gate closes that. It is PURE, it is evaluated from the verdict that was
 * already computed, and it answers exactly one question:
 *
 *     may this successful completion claim be ACTED ON?
 *
 * WHAT THE GATE DOES NOT DO, on purpose:
 *
 *   - it never touches the repository, never reverts, never removes and never
 *     rewrites anything. Held work is PRESERVED and parked, exactly as the
 *     unverified-resume path already preserves it. Fail-closed here means "do
 *     not adopt AND do not destroy", the same as everywhere else in D-134;
 *
 *   - it does not gate UNSUCCESSFUL terminal reports. A `STATUS=BLOCKED` or
 *     `STATUS=FAILED` report may still be terminal, because it makes no claim
 *     about work having landed: it cannot release a worktree (release already
 *     demands `successful === true`) and it cannot create successful-supersession
 *     truth (supersession already demands positive success). Gating it would
 *     resurrect finished-and-abandoned tasks for no safety gain;
 *
 *   - it does not invent evidence. When NO provenance record exists at all - a
 *     state row written before D-134 ever ran - the gate passes and says so.
 *     The dispatch path always computes a verdict, so a missing record means
 *     "no attempt of this worker version produced one", not "the answer was bad".
 */

export const COMPLETION_GATE = Object.freeze({
  /** Not a success claim (BLOCKED/FAILED/non-terminal). Nothing to gate. */
  PASSED_NOT_A_SUCCESS_CLAIM: "report_is_not_a_success_claim",
  /** `unchanged` or `task_attributed`: the claim rests on proven ground. */
  PASSED_PROVENANCE_VERIFIED: "commit_provenance_verified",
  /** Pre-D-134 record. Stated explicitly rather than silently treated as proof. */
  PASSED_NO_PROVENANCE_RECORD: "no_commit_provenance_record_exists",
  /** The one HELD reason: a success claim standing on an unverified range. */
  HELD_PROVENANCE_UNVERIFIED: "commit_provenance_unverified"
});

/**
 * Evaluate the gate for one task.
 *
 * `completion` is an `assessCompletion` result; `provenance` is a stored or
 * freshly computed `classifyCommitRange` record (or `null`).
 *
 * Returns `{ held, passed, reason, ... }`. `held === true` means: do NOT mark
 * this task completed or successful, do NOT release its worktree, do NOT emit a
 * completion-confirmed event, and do NOT let it retire any other task.
 */
export function evaluateCompletionGate({ completion, provenance, now = () => new Date() }) {
  const prov = provenance && typeof provenance === "object" ? provenance : null;
  const evidence = {
    provenance_verdict: prov?.verdict ?? null,
    provenance_reason: prov?.reason ?? null,
    head_before: prov?.head_before ?? null,
    head_after: prov?.head_after ?? null,
    head_now: prov?.head_now ?? null,
    // Full counts, never the capped detail-list lengths.
    unattributed_count: Number.isFinite(prov?.unattributed_count)
      ? prov.unattributed_count
      : (prov?.unattributed_commits?.length ?? 0),
    unattributed_commits: (prov?.unattributed_commits ?? []).map((c) => c?.sha).filter(Boolean),
    report_comment_id: completion?.reportCommentId ?? null,
    report_status: completion?.status ?? null,
    evaluated_at: now().toISOString()
  };

  if (completion?.complete !== true || completion?.successful !== true) {
    return { held: false, passed: true, reason: COMPLETION_GATE.PASSED_NOT_A_SUCCESS_CLAIM, ...evidence };
  }
  if (!prov) {
    return { held: false, passed: true, reason: COMPLETION_GATE.PASSED_NO_PROVENANCE_RECORD, ...evidence };
  }
  // BOTH halves are required, and neither is inferred from the other: a record
  // may carry a verified verdict with `verified` explicitly downgraded (that is
  // precisely what `provenanceForResume` does on drift), and a record from a
  // future version may carry a verdict this build does not know.
  if (isVerifiedVerdict(prov.verdict) && prov.verified === true) {
    return { held: false, passed: true, reason: COMPLETION_GATE.PASSED_PROVENANCE_VERIFIED, ...evidence };
  }
  return { held: true, passed: false, reason: COMPLETION_GATE.HELD_PROVENANCE_UNVERIFIED, ...evidence };
}

/**
 * Is a DURABLY RECORDED gate held for this task?
 *
 * This is the predicate the queue consults, and it is why the gate survives the
 * run that set it. The queue decides supersession from FRESH control-issue truth
 * - deliberately, so a terminal report beats stale bookkeeping - and that fresh
 * truth is exactly the `STATUS=COMPLETE` report the gate does not trust. Without
 * a durable local override, the held task would go on retiring older work on the
 * very next run, through a path that never looks at a provenance verdict.
 *
 * Positive and explicit: only `held === true` holds. A missing field, a legacy
 * row or a malformed value is not a hold.
 */
export function completionGateHeld(record) {
  return record?.completion_gate?.held === true;
}

/**
 * The status-comment body for a held gate. Says what was claimed, what was
 * actually proven, what the worker did NOT do, and what a human must decide.
 */
export function describeCompletionGate({ taskId, gate, worktreePath = null }) {
  return [
    `A TRUSTED report for ${taskId} claims SUCCESSFUL completion (comment ${gate.report_comment_id ?? "unknown"}, `
      + `STATUS=${gate.report_status ?? "unknown"}), but this worker cannot prove that the commits produced `
      + "during the attempt are this task's own work.",
    "",
    `COMMIT PROVENANCE VERDICT: ${gate.provenance_verdict ?? "unknown"} (verified=false)`,
    gate.provenance_reason ? `REASON: ${gate.provenance_reason}` : "",
    `HEAD observed: ${gate.head_before ?? "unknown"} -> ${gate.head_after ?? "unknown"}`
      + (gate.head_now && gate.head_now !== gate.head_after ? ` (now ${gate.head_now})` : ""),
    gate.unattributed_count > 0
      ? `UNEXPLAINED COMMITS (${gate.unattributed_count}): `
        + `${gate.unattributed_commits.map((s) => String(s).slice(0, 12)).join(", ") || "not listed"}`
      : "",
    worktreePath ? `WORKTREE (retained, untouched): ${worktreePath}` : "",
    "",
    "A moved HEAD is an OBSERVATION, not proof of authorship: the worker reads the ref twice and cannot",
    "see who moved it in between. A success claim that rests on commits it cannot account for is therefore",
    "not accepted, however trusted the report itself is.",
    "",
    "WHAT THE WORKER DID:",
    "  - parked the task as BLOCKED, NOT completed and NOT successful;",
    "  - did NOT emit a completion-confirmed event;",
    "  - did NOT release or remove the task's isolated worktree, and did NOT delete its claim;",
    "  - did NOT let this record retire (supersede) any older task;",
    "  - did NOT stash, reset, revert, clean, checkout over, force-push or rebase anything. Every commit",
    "    and every file is exactly where the attempt left it.",
    "",
    "This needs an explicit human reconciliation: establish what those commits are, against the actual",
    "diff, the PR and CI. If the work is good, issue a FRESH TASK_ID to carry it forward; if it is not,",
    "decide that deliberately. The worker will not replay a blocked task on its own."
  ].filter((l) => l !== "").join("\n");
}
