/**
 * Deterministisk pseudo-tilfeldighet for egenskapstester (fast seed, ingen ny avhengighet).
 * mulberry32: liten, rask og reproduserbar - samme seed gir alltid samme sekvens, så en feil kan gjentas.
 */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export class Rng {
  private readonly next: () => number;
  constructor(seed: number) {
    this.next = mulberry32(seed);
  }
  float(): number {
    return this.next();
  }
  int(maxExclusive: number): number {
    return Math.floor(this.next() * maxExclusive);
  }
  pick<T>(items: readonly T[]): T {
    if (items.length === 0) throw new Error("pick_from_empty");
    return items[this.int(items.length)] as T;
  }
  /** Delmengde der hvert element er med med sannsynlighet `p`. */
  subset<T>(items: readonly T[], p = 0.4): T[] {
    return items.filter(() => this.next() < p);
  }
  shuffle<T>(items: readonly T[]): T[] {
    const out = [...items];
    for (let i = out.length - 1; i > 0; i -= 1) {
      const j = this.int(i + 1);
      [out[i], out[j]] = [out[j] as T, out[i] as T];
    }
    return out;
  }
}
